# Generates StatsTrimmer/Locales.lua: the client strings Stats Trimmer shows, in every language it offers,
# taken from Forever's GlobalStrings on wago.tools. Run it again when the client build changes.
# Usage: ./scripts/update-locales.ps1 [-Build 1.60.1.70338]
param([string]$Build = "1.60.1.70338")

$ErrorActionPreference = "Stop"

# Languages with the Latin alphabet, which every client's font can show. Other clients get their own
# language from the game itself.
$locales = @("enUS", "deDE", "esES", "esMX", "frFR", "itIT", "ptBR")
# Interface texts, besides every ITEM_MOD_*_SHORT stat name
$uiKeys = @("CTRL_KEY", "ALT_KEY", "SHIFT_KEY", "RESET", "PREVIEW", "COLORS", "ITEM_BIND_ON_EQUIP")

$root = Split-Path -Parent $PSScriptRoot
$output = Join-Path $root "StatsTrimmer/Locales.lua"
$download = Join-Path ([System.IO.Path]::GetTempPath()) "StatsTrimmer-GlobalStrings.csv"

function ConvertTo-LuaString([string]$text) {
	$escaped = $text.Replace('\', '\\').Replace('"', '\"').Replace("`r", '\r').Replace("`n", '\n')
	return '"' + $escaped + '"'
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("-- Generated by scripts/update-locales.ps1 from the GlobalStrings of build $Build")
$lines.Add("-- (https://wago.tools/db2/GlobalStrings). Don't edit it by hand: run the script again.")
$lines.Add("-- These are Blizzard's texts, not covered by the addon's license.")
$lines.Add("local _, ns = ...")
$lines.Add("")
$lines.Add("-- Languages in menu order")
$lines.Add("ns.LOCALES = { " + (($locales | ForEach-Object { '"' + $_ + '"' }) -join ", ") + " }")
$lines.Add("")
$lines.Add("ns.LOCALE_STRINGS = {")

try {
	foreach ($locale in $locales) {
		$url = "https://wago.tools/db2/GlobalStrings/csv?build=$Build&locale=$locale"
		Invoke-WebRequest -Uri $url -OutFile $download -UseBasicParsing
		$strings = @{}
		foreach ($row in Import-Csv -Path $download -Encoding utf8) {
			if ($row.BaseTag -match '^ITEM_MOD_.+_SHORT$' -or $uiKeys -contains $row.BaseTag) {
				$strings[$row.BaseTag] = $row.TagText_lang
			}
		}

		$statCount = @($strings.Keys | Where-Object { $_ -like "ITEM_MOD_*" }).Count
		$missing = @($uiKeys | Where-Object { -not $strings.ContainsKey($_) })
		if ($statCount -lt 100 -or $missing.Count -gt 0) {
			throw "$locale looks incomplete: $statCount stat names, missing $($missing -join ', ')"
		}
		Write-Output ("{0}: {1} stat names" -f $locale, $statCount)

		$lines.Add("`t$locale = {")
		foreach ($key in ($strings.Keys | Sort-Object -CaseSensitive)) {
			$lines.Add("`t`t$key = $(ConvertTo-LuaString $strings[$key]),")
		}
		$lines.Add("`t},")
	}
}
finally {
	Remove-Item $download -ErrorAction SilentlyContinue
}

$lines.Add("}")
[System.IO.File]::WriteAllText($output, ($lines -join "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
if (Get-Command stylua -ErrorAction SilentlyContinue) {
	stylua $output
}
Write-Output "Wrote $output"
